#!/usr/bin/env python3
"""Automated Pull Request Reviewer for Kaizen Agent.

Inspects open PRs against linked issues, verifies functional correctness,
evaluates AGENTS.md compliance, submits an explicit APPROVE or REQUEST_CHANGES
verdict via GitHub CLI (gh), and automatically squashes and merges approved PRs.
"""

from __future__ import annotations

import argparse
import json
import logging
import os
import re
import subprocess
import sys
from pathlib import Path
from typing import Any

from pydantic import BaseModel, Field

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
logger = logging.getLogger("pr_reviewer")

IGNORE_DIFF_EXTENSIONS = {
    ".png",
    ".jpg",
    ".jpeg",
    ".gif",
    ".ico",
    ".webp",
    ".pdf",
    ".mp4",
    ".svg",
    "package-lock.json",
    "yarn.lock",
    "pnpm-lock.yaml",
}

MAX_DIFF_PER_FILE_LINES = 250
MAX_TOTAL_DIFF_CHARS = 35_000


class ReviewVerdict(BaseModel):
    decision: str = Field(description="Strictly 'APPROVE' or 'REQUEST_CHANGES'")
    summary: str = Field(description="Executive summary of the review")
    scope_analysis: str = Field(description="Analysis of linked issue scope and traceability")
    correctness_and_functionality: str = Field(
        description="Technical evaluation of code correctness and runtime behavior"
    )
    repository_standards: str = Field(
        description="Assessment of AGENTS.md compliance, project layout, models, and styling"
    )
    required_changes: list[str] = Field(
        default_factory=list, description="List of blocking issues required before approval"
    )
    recommendations: list[str] = Field(
        default_factory=list, description="List of non-blocking suggestions"
    )

    def to_markdown(self, pr_author: str, current_user: str) -> str:
        icon = "✅" if self.decision == "APPROVE" else "❌"
        verdict_badge = f"# {icon} Kaizen PR Review: **{self.decision}**\n\n"

        author_notice = ""
        if pr_author and current_user and pr_author.lower() == current_user.lower():
            author_notice = (
                "> [!NOTE]\n"
                "> **GitHub Self-Review Notice**: Because GitHub restricts PR authors from "
                "submitting formal approve/request-changes reviews on their own pull requests, "
                f"this review is recorded as a review comment with explicit verdict **{self.decision}**.\n\n"
            )

        body = (
            f"{verdict_badge}"
            f"{author_notice}"
            f"### 📋 Executive Summary\n{self.summary}\n\n"
            f"### 🎯 Linked Issue Scope & Traceability\n{self.scope_analysis}\n\n"
            f"### ⚙️ Correctness & Functional Verification\n{self.correctness_and_functionality}\n\n"
            f"### 🏛️ Repository Architecture & AGENTS.md Conformance\n{self.repository_standards}\n\n"
        )

        if self.required_changes:
            body += "### ⛔ Required Changes (Blockers)\n"
            for item in self.required_changes:
                body += f"- [ ] {item}\n"
            body += "\n"

        if self.recommendations:
            body += "### 💡 Suggestions & Non-blocking Improvements\n"
            for item in self.recommendations:
                body += f"- {item}\n"
            body += "\n"

        body += (
            "---\n*Automated review generated by Kaizen PR Reviewer with Gemini 2.5 on Vertex AI.*"
        )
        return body


def run_cmd(cmd: list[str], cwd: Path | None = None) -> tuple[int, str, str]:
    """Runs a shell command and returns (exit_code, stdout, stderr)."""
    try:
        proc = subprocess.run(
            cmd,
            cwd=str(cwd) if cwd else None,
            capture_output=True,
            text=True,
            check=False,
        )
        return proc.returncode, proc.stdout.strip(), proc.stderr.strip()
    except Exception as exc:
        return 1, "", str(exc)


def get_current_user() -> str:
    code, stdout, _ = run_cmd(["gh", "api", "user", "--jq", ".login"])
    if code == 0 and stdout:
        return stdout.strip()
    return ""


def get_open_prs() -> list[dict[str, Any]]:
    cmd = [
        "gh",
        "pr",
        "list",
        "--state",
        "open",
        "--json",
        "number,title,body,headRefName,baseRefName,author,url,updatedAt",
    ]
    code, stdout, stderr = run_cmd(cmd)
    if code != 0:
        logger.error(f"Failed to list open PRs: {stderr}")
        return []
    try:
        return json.loads(stdout)
    except Exception as exc:
        logger.error(f"Failed to parse PR list JSON: {exc}")
        return []


def get_pr_details(pr_number: int) -> dict[str, Any] | None:
    cmd = [
        "gh",
        "pr",
        "view",
        str(pr_number),
        "--json",
        "number,title,body,headRefName,baseRefName,author,url,updatedAt,commits,reviews,files",
    ]
    code, stdout, stderr = run_cmd(cmd)
    if code != 0:
        logger.error(f"Failed to fetch PR #{pr_number}: {stderr}")
        return None
    try:
        return json.loads(stdout)
    except Exception as exc:
        logger.error(f"Failed to parse PR #{pr_number} details: {exc}")
        return None


def get_pr_diff(pr_number: int) -> str:
    code, stdout, stderr = run_cmd(["gh", "pr", "diff", str(pr_number)])
    if code != 0:
        logger.warning(f"Failed to fetch diff for PR #{pr_number}: {stderr}")
        return ""
    return stdout


def get_closing_issues(pr_number: int) -> list[int]:
    """Query closing issue numbers via GitHub GraphQL API."""
    query = """
    query($owner: String!, $repo: String!, $number: Int!) {
      repository(owner: $owner, name: $repo) {
        pullRequest(number: $number) {
          closingIssuesReferences(first: 10) {
            nodes {
              number
            }
          }
        }
      }
    }
    """
    code_owner, owner_repo, _ = run_cmd(
        ["gh", "repo", "view", "--json", "nameWithOwner", "--jq", ".nameWithOwner"]
    )
    if code_owner != 0 or "/" not in owner_repo:
        return []
    owner, repo = owner_repo.split("/", 1)

    cmd = [
        "gh",
        "api",
        "graphql",
        "-f",
        f"query={query}",
        "-F",
        f"owner={owner}",
        "-F",
        f"repo={repo}",
        "-F",
        f"number={pr_number}",
    ]
    code, stdout, _ = run_cmd(cmd)
    if code != 0:
        return []
    try:
        data = json.loads(stdout)
        nodes = (
            data.get("data", {})
            .get("repository", {})
            .get("pullRequest", {})
            .get("closingIssuesReferences", {})
            .get("nodes", [])
        )
        return [node["number"] for node in nodes if "number" in node]
    except Exception:
        return []


def extract_linked_issues(pr_data: dict[str, Any]) -> list[int]:
    """Extracts linked issues from closingReferences, body keywords, branch name, and commit messages."""
    found: set[int] = set()
    pr_number = pr_data.get("number", 0)

    # 1. Closing issues references
    for iss in get_closing_issues(pr_number):
        found.add(iss)

    # 2. PR body regex keywords
    body = pr_data.get("body") or ""
    # Matches: fixes #12, closes #12, resolves #12, refs #12, #12
    pattern = r"(?:(?:fix|close|resolve|ref|address)es?|refs?)?\s*#(\d+)"
    for match in re.finditer(pattern, body, re.IGNORECASE):
        found.add(int(match.group(1)))

    # 3. Branch name (e.g. feat/31-operator-dashboard or feat/issue-25)
    branch = pr_data.get("headRefName") or ""
    branch_match = re.search(r"/(?:issue-?)?(\d+)[-_]", branch, re.IGNORECASE)
    if branch_match:
        found.add(int(branch_match.group(1)))

    # 4. Commit messages
    commits = pr_data.get("commits") or []
    for commit in commits:
        headline = commit.get("messageHeadline") or ""
        msg_body = commit.get("messageBody") or ""
        for match in re.finditer(r"#(\d+)", f"{headline} {msg_body}"):
            found.add(int(match.group(1)))

    # Filter out self-reference if PR number matched
    found.discard(pr_number)
    return sorted(found)


def get_issue_details(issue_number: int) -> dict[str, Any] | None:
    cmd = [
        "gh",
        "issue",
        "view",
        str(issue_number),
        "--json",
        "number,title,body,state,labels",
    ]
    code, stdout, stderr = run_cmd(cmd)
    if code != 0:
        logger.warning(f"Could not view issue #{issue_number}: {stderr}")
        return None
    try:
        return json.loads(stdout)
    except Exception:
        return None


def clean_diff(raw_diff: str) -> str:
    """Filters out binary and lockfile diffs, truncating large individual files."""
    if not raw_diff:
        return ""

    file_chunks = raw_diff.split("diff --git ")
    cleaned_chunks: list[str] = []

    for chunk in file_chunks:
        if not chunk.strip():
            continue
        first_line = chunk.splitlines()[0] if chunk.splitlines() else ""
        # Check ignored extensions
        if any(
            chunk.startswith(f"a/{ext}") or f"/{ext} " in first_line or ext in first_line
            for ext in IGNORE_DIFF_EXTENSIONS
        ):
            cleaned_chunks.append(f"{first_line}\n[Binary / asset / lockfile diff omitted]")
            continue

        lines = chunk.splitlines()
        if len(lines) > MAX_DIFF_PER_FILE_LINES:
            kept = "\n".join(lines[:MAX_DIFF_PER_FILE_LINES])
            cleaned_chunks.append(
                f"{kept}\n... [Truncated {len(lines) - MAX_DIFF_PER_FILE_LINES} lines] ..."
            )
        else:
            cleaned_chunks.append(chunk)

    total_diff = "\ndiff --git ".join(cleaned_chunks)
    if len(total_diff) > MAX_TOTAL_DIFF_CHARS:
        total_diff = (
            total_diff[:MAX_TOTAL_DIFF_CHARS] + "\n... [Total diff truncated for token limit] ..."
        )

    return total_diff


def build_review_prompt(
    pr_data: dict[str, Any],
    issues: list[dict[str, Any]],
    cleaned_diff: str,
) -> str:
    pr_number = pr_data.get("number")
    pr_title = pr_data.get("title", "")
    pr_body = pr_data.get("body", "")
    pr_branch = pr_data.get("headRefName", "")
    files = [f.get("path", "") for f in pr_data.get("files", [])]

    issues_context = ""
    if issues:
        for iss in issues:
            labels = ", ".join(lbl.get("name", "") for lbl in iss.get("labels", []))
            issues_context += (
                f"\n--- Linked Issue #{iss['number']}: {iss.get('title')} ---\n"
                f"State: {iss.get('state')}\n"
                f"Labels: {labels}\n"
                f"Description:\n{iss.get('body')}\n"
            )
    else:
        issues_context = "\n[No linked GitHub issues identified. Note: PR must be evaluated for missing traceability.]\n"

    prompt = f"""You are the Kaizen Lead AI Code Reviewer.
Your task is to perform an authoritative, rigorous review of Pull Request #{pr_number}.

You must explicitly evaluate:
1. SCOPE OF LINKED ISSUE(S):
   Compare what was requested in the linked issue(s) against what this PR implements.
   - Did the PR complete all required acceptance criteria?
   - Is there scope creep or unrelated changes?
   - If no issue is linked, assess whether the PR lacks proper tracking context.

2. FUNCTIONALITY & CORRECTNESS ("Is it working like intended?"):
   - Deeply inspect the implementation: does it work as intended?
   - Are there functional bugs, unhandled errors, mock fallbacks disguised as real features, broken types, or data schema mismatches?
   - Check UI components: are they connected to endpoints or faking telemetry?
   - Check backend logic: are models correctly defined, async handled, edge cases addressed?

3. REPOSITORY ARCHITECTURE & STANDARDS (AGENTS.md):
   - Project Layout: All frontend code must live in `apps/web/` or `apps/mobile/`. Rogue root directories like `dashboard_frontend/` or `dashboard/` violate the layout and break `mise.toml` / Firebase Hosting.
   - Schemas: `backend/core/models.py` is the single source of truth for Pydantic models.
   - Backend async: all handlers and agent functions must be `async def`.
   - UI Design: Lumina Slate liquid glass light mode (no dark mode, CSS custom property tokens, no Tailwind/shadcn).
   - Test coverage: new features or tools must include tests in `tests/`.

4. EXPLICIT VERDICT:
   You MUST choose strictly either "APPROVE" or "REQUEST_CHANGES".
   - If there are architectural violations (e.g. invalid directory structure), functional bugs, broken contracts, or critical unfulfilled issue criteria, you MUST output "REQUEST_CHANGES".
   - Only output "APPROVE" if the implementation is correct, works as intended, satisfies the issue scope, and adheres to repository conventions.

=== PULL REQUEST DETAILS ===
Number: #{pr_number}
Title: {pr_title}
Branch: {pr_branch}
Changed Files ({len(files)} files):
{chr(10).join(f"- {f}" for f in files[:80])}

PR Body:
{pr_body}

=== LINKED ISSUES ===
{issues_context}

=== CODE DIFF ===
{cleaned_diff}

=== OUTPUT FORMAT ===
You must respond with valid JSON adhering to the following schema:
{{
  "decision": "APPROVE" or "REQUEST_CHANGES",
  "summary": "Concise 2-3 sentence executive review summary.",
  "scope_analysis": "Detailed analysis comparing PR changes against the linked issue requirements.",
  "correctness_and_functionality": "Technical evaluation of whether the implementation works as intended, potential bugs, data flow, and runtime validity.",
  "repository_standards": "Assessment of directory layout, AGENTS.md conventions, typing, and architectural consistency.",
  "required_changes": [
    "List of blocking items that must be resolved if REQUEST_CHANGES. Leave empty if APPROVE."
  ],
  "recommendations": [
    "Optional list of suggestions, polish, or non-blocking tips."
  ]
}}
"""
    return prompt


def evaluate_with_gemini(prompt: str) -> ReviewVerdict | None:
    """Calls Gemini 2.5 using google.genai with Vertex AI or Gemini API key."""
    try:
        from google import genai
        from google.genai import types

        client = None
        api_key = os.environ.get("GEMINI_API_KEY") or os.environ.get("GOOGLE_API_KEY")
        if api_key:
            client = genai.Client(api_key=api_key)
        else:
            project_id = os.environ.get("GCP_PROJECT_ID") or "kaizen-lab-2026"
            region = os.environ.get("GCP_REGION") or "us-central1"
            client = genai.Client(vertexai=True, project=project_id, location=region)

        response = client.models.generate_content(
            model="gemini-2.5-flash",
            contents=prompt,
            config=types.GenerateContentConfig(
                response_mime_type="application/json",
                response_schema=ReviewVerdict,
                temperature=0.2,
            ),
        )

        verdict = response.parsed
        if isinstance(verdict, ReviewVerdict):
            decision = verdict.decision.strip().upper()
            if decision not in ("APPROVE", "REQUEST_CHANGES"):
                verdict.decision = "REQUEST_CHANGES"
            return verdict

        raw_text = response.text or ""
        data = json.loads(raw_text)
        decision = data.get("decision", "REQUEST_CHANGES").strip().upper()
        if decision not in ("APPROVE", "REQUEST_CHANGES"):
            decision = "REQUEST_CHANGES"

        return ReviewVerdict(
            decision=decision,
            summary=data.get("summary", ""),
            scope_analysis=data.get("scope_analysis", ""),
            correctness_and_functionality=data.get("correctness_and_functionality", ""),
            repository_standards=data.get("repository_standards", ""),
            required_changes=data.get("required_changes", []),
            recommendations=data.get("recommendations", []),
        )
    except Exception as exc:
        logger.warning(f"Gemini evaluation failed or unavailable: {exc}")
        return None


def evaluate_with_heuristics(
    pr_data: dict[str, Any],
    issues: list[dict[str, Any]],
) -> ReviewVerdict:
    """Deterministic fallback reviewer when LLM credentials are not configured."""
    files = [f.get("path", "") for f in pr_data.get("files", [])]
    required_changes: list[str] = []
    recommendations: list[str] = []

    # Check for unauthorized root directories
    rogue_dirs = {"dashboard_frontend", "dashboard", "frontend", "client"}
    for f in files:
        top_level = f.split("/")[0] if "/" in f else ""
        if top_level in rogue_dirs:
            required_changes.append(
                f"Directory layout violation: `{top_level}/` violates the monorepo structure. "
                "Per AGENTS.md, frontend applications must reside inside `apps/web/` or `apps/mobile/`."
            )
            break

    # Check linked issue
    if not issues:
        recommendations.append(
            "Traceability warning: No linked GitHub issue found in PR description or branch name. "
            "Please link the tracking issue (e.g., `Fixes #31`)."
        )

    # Check tests
    has_test = any("test" in f.lower() for f in files)
    if not has_test and any(f.startswith("backend/") for f in files):
        recommendations.append(
            "Consider adding unit tests under `tests/` for new backend features."
        )

    if required_changes:
        decision = "REQUEST_CHANGES"
        summary = "Pull request contains architectural or layout violations that must be addressed."
    else:
        decision = "APPROVE"
        summary = "Static heuristic checks passed with no blocking architectural violations."

    return ReviewVerdict(
        decision=decision,
        summary=summary,
        scope_analysis=f"Inspected against {len(issues)} linked issue(s)."
        if issues
        else "No linked issues provided.",
        correctness_and_functionality="Automated heuristic check inspected file paths, extensions, and directory structure.",
        repository_standards="AGENTS.md directory layout verified.",
        required_changes=required_changes,
        recommendations=recommendations,
    )


def submit_review(
    pr_number: int,
    verdict: ReviewVerdict,
    pr_author: str,
    current_user: str,
    dry_run: bool = False,
) -> bool:
    """Submits the review via GitHub CLI (gh pr review)."""
    markdown = verdict.to_markdown(pr_author, current_user)

    if dry_run:
        print("\n" + "=" * 80)
        print(f"DRY RUN: Generated Review for PR #{pr_number}")
        print("=" * 80)
        print(markdown)
        print("=" * 80 + "\n")
        return True

    # If the current user is the PR author, gh will reject --approve / --request-changes with 422
    is_self = pr_author and current_user and pr_author.lower() == current_user.lower()

    if is_self:
        logger.info(
            f"PR #{pr_number} authored by current user ({pr_author}). Submitting as review comment..."
        )
        cmd = ["gh", "pr", "review", str(pr_number), "--comment", "-b", markdown]
    elif verdict.decision == "APPROVE":
        logger.info(f"Submitting APPROVE review for PR #{pr_number}...")
        cmd = ["gh", "pr", "review", str(pr_number), "--approve", "-b", markdown]
    else:
        logger.info(f"Submitting REQUEST_CHANGES review for PR #{pr_number}...")
        cmd = ["gh", "pr", "review", str(pr_number), "--request-changes", "-b", markdown]

    code, stdout, stderr = run_cmd(cmd)
    if code != 0:
        logger.error(f"Failed to submit review for PR #{pr_number}: {stderr}")
        return False

    logger.info(f"Review successfully posted for PR #{pr_number} (Verdict: {verdict.decision}).")
    return True


def merge_approved_pr(pr_number: int, dry_run: bool = False) -> bool:
    """Executes squash and merge for approved PR."""
    if dry_run:
        logger.info(
            f"DRY RUN: Would squash and merge PR #{pr_number} (gh pr merge {pr_number} --squash --delete-branch)."
        )
        return True

    logger.info(f"Proceeding to squash and merge PR #{pr_number}...")
    cmd = ["gh", "pr", "merge", str(pr_number), "--squash", "--delete-branch"]
    code, stdout, stderr = run_cmd(cmd)

    if code == 0:
        logger.info(f"Successfully squash-merged PR #{pr_number}!")
        return True

    logger.warning(
        f"Immediate squash-merge encountered notice/error: {stderr}. Checking if auto-merge helps..."
    )
    # Attempt with --auto if branch protection rules require checks first
    auto_cmd = ["gh", "pr", "merge", str(pr_number), "--squash", "--delete-branch", "--auto"]
    auto_code, auto_out, auto_err = run_cmd(auto_cmd)
    if auto_code == 0:
        logger.info(f"Successfully enabled auto-merge for PR #{pr_number}.")
        return True

    logger.error(f"Failed to merge PR #{pr_number}: {stderr or auto_err}")
    return False


def review_pull_request(
    pr_number: int,
    auto_merge: bool = True,
    dry_run: bool = False,
    force: bool = False,
) -> ReviewVerdict | None:
    logger.info(f"Inspecting Pull Request #{pr_number}...")
    pr_data = get_pr_details(pr_number)
    if not pr_data:
        logger.error(f"Could not retrieve details for PR #{pr_number}.")
        return None

    pr_author = pr_data.get("author", {}).get("login", "")
    current_user = get_current_user()

    # 1. Linked Issues Discovery
    linked_issue_ids = extract_linked_issues(pr_data)
    logger.info(f"PR #{pr_number} linked issues identified: {linked_issue_ids}")
    issues = []
    for issue_id in linked_issue_ids:
        iss = get_issue_details(issue_id)
        if iss:
            issues.append(iss)

    # 2. Extract and Clean Diff
    raw_diff = get_pr_diff(pr_number)
    cleaned_diff = clean_diff(raw_diff)

    # 3. Formulate Prompt & Evaluate
    prompt = build_review_prompt(pr_data, issues, cleaned_diff)
    logger.info("Evaluating PR against linked issue scope, correctness, and AGENTS.md standards...")

    verdict = evaluate_with_gemini(prompt)
    if not verdict:
        logger.warning("Falling back to deterministic heuristic reviewer...")
        verdict = evaluate_with_heuristics(pr_data, issues)

    logger.info(f"Review verdict for PR #{pr_number}: {verdict.decision}")

    # 4. Submit Review
    submitted = submit_review(
        pr_number=pr_number,
        verdict=verdict,
        pr_author=pr_author,
        current_user=current_user,
        dry_run=dry_run,
    )

    # 5. Auto Squash & Merge if Approved
    if verdict.decision == "APPROVE" and auto_merge and submitted:
        merge_approved_pr(pr_number, dry_run=dry_run)
    elif verdict.decision != "APPROVE":
        logger.info(f"PR #{pr_number} requested changes. Squash-and-merge skipped.")

    return verdict


def main() -> None:
    parser = argparse.ArgumentParser(description="Kaizen Agent PR Reviewer & Merge Automation")
    parser.add_argument("--pr", type=int, help="Single PR number to review")
    parser.add_argument("--all-open", action="store_true", help="Review all open PRs in repository")
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Generate review and log to console without submitting",
    )
    parser.add_argument(
        "--no-auto-merge",
        action="store_true",
        help="Disable immediate squash and merge on approval",
    )
    parser.add_argument(
        "--force", action="store_true", help="Force review even if already reviewed"
    )

    args = parser.parse_args()
    auto_merge = not args.no_auto_merge

    if args.pr:
        review_pull_request(
            pr_number=args.pr,
            auto_merge=auto_merge,
            dry_run=args.dry_run,
            force=args.force,
        )
    elif args.all_open:
        open_prs = get_open_prs()
        if not open_prs:
            logger.info("No open pull requests found.")
            return
        logger.info(f"Found {len(open_prs)} open pull request(s) to review.")
        for pr in open_prs:
            pr_num = pr.get("number")
            if pr_num:
                review_pull_request(
                    pr_number=pr_num,
                    auto_merge=auto_merge,
                    dry_run=args.dry_run,
                    force=args.force,
                )
    else:
        parser.print_help()
        sys.exit(1)


if __name__ == "__main__":
    main()
